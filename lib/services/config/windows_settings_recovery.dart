import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

/// Recovers Windows SharedPreferences when a portable build is first run
/// under a different historical app-data identity.
///
/// The current identity derives from windows/runner/Runner.rc:
/// CompanyName=com.example and ProductName=playtorrio. Never move, delete or
/// replace a nonempty current store. The snapshot is a LOCAL backup only.
class WindowsSettingsRecovery {
  static WindowsSettingsAudit? lastAudit;

  static Future<WindowsSettingsAudit> prepare({
    String? roamingRoot,
    bool forTesting = false,
  }) async {
    if (!Platform.isWindows && !forTesting) {
      return const WindowsSettingsAudit('not-windows', 0, false);
    }
    final root = roamingRoot ?? Platform.environment['APPDATA'];
    if (root == null || root.isEmpty) {
      return const WindowsSettingsAudit('roaming-appdata-unavailable', 0, false);
    }

    final current = File(p.join(root, 'com.example', 'playtorrio',
        'shared_preferences.json'));
    final backup = File(p.join(
        root, 'PlayTorrio', 'settings-recovery', 'shared_preferences.json'));
    final alternatives = <File>[
      backup,
      File(p.join(root, 'playtorrio', 'shared_preferences.json')),
      File(p.join(root, 'PlayTorrio', 'shared_preferences.json')),
      File(p.join(root, 'com.playtorrio', 'playtorrio',
          'shared_preferences.json')),
      File(p.join(root, 'com.example', 'PlayTorrio',
          'shared_preferences.json')),
    ];

    try {
      var values = await _readValid(current);
      var recovered = false;
      // A valid current store always wins, even when a backup has more keys.
      if (values.isEmpty) {
        for (final candidate in alternatives) {
          final oldValues = await _readValid(candidate);
          if (oldValues.isEmpty) continue;
          // Preserve the original file; do not modify the source or secrets.
          await current.parent.create(recursive: true);
          await current.writeAsString(jsonEncode(oldValues), flush: true);
          values = oldValues;
          recovered = true;
          break;
        }
      }
      if (values.isNotEmpty) {
        // Keep a fallback copy when current storage is healthy. Do not wipe a
        // good previous snapshot with a partial/empty brand-new install.
        final snapshot = await _readValid(backup);
        if (recovered || values.length >= snapshot.length) {
          await backup.parent.create(recursive: true);
          await backup.writeAsString(jsonEncode(values), flush: true);
        }
      }
      final result = WindowsSettingsAudit(
        recovered ? 'recovered-from-existing-profile' :
            values.isNotEmpty ? 'existing-profile' : 'empty-profile',
        values.length, recovered,
      );
      lastAudit = result;
      return result;
    } catch (error) {
      // Never block app launch or expose preference contents to diagnostics.
      final result = WindowsSettingsAudit(
          'storage-access-failed-${error.runtimeType}', 0, false);
      lastAudit = result;
      return result;
    }
  }

  static Future<Map<String, Object?>> _readValid(File file) async {
    if (!await file.exists()) return {};
    try {
      if (await file.length() > 4 * 1024 * 1024) return {};
      final decoded = jsonDecode(await file.readAsString());
      if (decoded is! Map<String, dynamic>) return {};
      // Only restore files generated by Flutter SharedPreferences.
      if (!decoded.keys.any((key) => key.startsWith('flutter.'))) return {};
      return Map<String, Object?>.from(decoded);
    } catch (_) {
      return {};
    }
  }
}

class WindowsSettingsAudit {
  final String state;
  final int preferenceCount;
  final bool recovered;

  const WindowsSettingsAudit(this.state, this.preferenceCount, this.recovered);
}
